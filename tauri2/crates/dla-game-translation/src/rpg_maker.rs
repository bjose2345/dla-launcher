//! RPG Maker MV and MZ load the plugins listed in `js/plugins.js`, a script
//! that assigns a JSON array to `$plugins`. The launcher's two plugins go
//! into that list: the settings plugin first, so it can change other
//! plugins' settings before they load, and the main plugin last, so its
//! changes to the engine come after everyone else's.

use serde_json::Value;

pub const PLUGINS: [(&str, &str); 2] = [
    (
        "DLA_TranslateSettings.js",
        include_str!("../plugins/rpg-maker/DLA_TranslateSettings.js"),
    ),
    (
        "DLA_Translate.js",
        include_str!("../plugins/rpg-maker/DLA_Translate.js"),
    ),
];

// As RPG Maker's editor writes them, with each plugin's own description.
const FIRST_ENTRY: &str = r#"{"name":"DLA_TranslateSettings","status":true,"description":"Machine translation from DLA Launcher: other plugins' settings. Must be first.","parameters":{}}"#;
const LAST_ENTRY: &str = r#"{"name":"DLA_Translate","status":true,"description":"Machine translation from DLA Launcher, with your own translator. Must be last.","parameters":{}}"#;
const NAMES: [&str; 2] = ["DLA_TranslateSettings", "DLA_Translate"];

#[derive(Debug, Eq, PartialEq)]
pub struct UnknownLayout;

/// Whether the plugin list already loads the launcher's plugins.
pub fn lists_our_plugins(list: &str) -> Result<bool, UnknownLayout> {
    Ok(entries(list)?.iter().any(is_ours))
}

/// The list with the launcher's plugins added, everything else unchanged.
pub fn add_our_plugins(list: &str) -> Result<String, UnknownLayout> {
    entries(list)?;
    let (open, close) = bounds(list).ok_or(UnknownLayout)?;
    let body = &list[open + 1..close];
    let kept = body.trim_end();
    let trailing = &body[kept.len()..];
    let added = if kept.trim().is_empty() {
        format!(
            "{}\n{FIRST_ENTRY},\n{LAST_ENTRY}\n{}",
            &list[..=open],
            &list[close..]
        )
    } else {
        format!(
            "{}\n{FIRST_ENTRY},{kept},\n{LAST_ENTRY}{trailing}{}",
            &list[..=open],
            &list[close..]
        )
    };
    entries(&added)?;
    Ok(added)
}

/// The list without the launcher's plugins, for a list that changed after
/// they were added (so the original cannot simply be put back).
pub fn remove_our_plugins(list: &str) -> Result<String, UnknownLayout> {
    let mut removed = list.to_owned();
    for (entry, before, after) in [(FIRST_ENTRY, "\n", ","), (LAST_ENTRY, ",\n", "")] {
        for candidate in [
            format!("{before}{entry}{after}"),
            format!("{entry}{after}"),
            format!("{before}{entry}"),
        ] {
            if let Some(at) = removed.find(&candidate) {
                removed.replace_range(at..at + candidate.len(), "");
                break;
            }
        }
    }
    if lists_our_plugins(&removed)? {
        removed = remove_lines(&removed)?;
    }
    entries(&removed)?;
    Ok(removed)
}

// After the editor saved the list again: one plugin per line.
fn remove_lines(list: &str) -> Result<String, UnknownLayout> {
    let mut lines = list
        .split_inclusive('\n')
        .filter(|line| {
            let entry = line.trim().trim_end_matches(',');
            serde_json::from_str::<Value>(entry)
                .map(|value| !is_ours(&value))
                .unwrap_or(true)
        })
        .map(str::to_owned)
        .collect::<Vec<_>>();
    // The entry now last must not keep its comma.
    if let Some(close) = lines
        .iter()
        .rposition(|line| line.trim_start().starts_with(']'))
        && let Some(last) = close.checked_sub(1)
        && let Some(line) = lines.get_mut(last)
        && line.trim_end().ends_with("},")
    {
        let comma = line.trim_end().len() - 1;
        line.remove(comma);
    }
    Ok(lines.concat())
}

fn is_ours(entry: &Value) -> bool {
    entry["name"]
        .as_str()
        .is_some_and(|name| NAMES.contains(&name))
}

fn bounds(list: &str) -> Option<(usize, usize)> {
    let start = list.find("$plugins")?;
    let open = start + list[start..].find('[')?;
    let close = list.rfind(']')?;
    (close > open).then_some((open, close))
}

fn entries(list: &str) -> Result<Vec<Value>, UnknownLayout> {
    let (open, close) = bounds(list).ok_or(UnknownLayout)?;
    serde_json::from_str(&list[open..=close]).map_err(|_| UnknownLayout)
}

#[cfg(test)]
mod tests {
    use super::*;

    const EDITOR_LIST: &str = "// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n{\"name\":\"TorigoyaMZ_NotifyMessage\",\"status\":true,\"description\":\"通知\",\"parameters\":{}},\n{\"name\":\"MessageWindowHidden\",\"status\":false,\"description\":\"\",\"parameters\":{\"triggerButton\":\"[\\\"右クリック\\\"]\"}}\n];\n";

    fn names(list: &str) -> Vec<String> {
        entries(list)
            .unwrap()
            .iter()
            .map(|entry| entry["name"].as_str().unwrap().to_owned())
            .collect()
    }

    #[test]
    fn adds_the_settings_plugin_first_and_the_main_plugin_last() {
        let added = add_our_plugins(EDITOR_LIST).unwrap();
        assert_eq!(
            names(&added),
            [
                "DLA_TranslateSettings",
                "TorigoyaMZ_NotifyMessage",
                "MessageWindowHidden",
                "DLA_Translate"
            ]
        );
        assert!(added.starts_with("// Generated by RPG Maker."));
        assert!(added.ends_with("\n];\n"));
        assert!(lists_our_plugins(&added).unwrap());
        assert!(!lists_our_plugins(EDITOR_LIST).unwrap());
        assert_eq!(remove_our_plugins(&added).unwrap(), EDITOR_LIST);
    }

    #[test]
    fn handles_an_empty_list_and_a_list_on_one_line() {
        let empty = "var $plugins =\n[\n];\n";
        let added = add_our_plugins(empty).unwrap();
        assert_eq!(names(&added), ["DLA_TranslateSettings", "DLA_Translate"]);
        assert_eq!(
            names(&remove_our_plugins(&added).unwrap()),
            Vec::<String>::new()
        );

        let one_line = r#"var $plugins = [{"name":"A","status":true,"parameters":{}}];"#;
        let added = add_our_plugins(one_line).unwrap();
        assert_eq!(
            names(&added),
            ["DLA_TranslateSettings", "A", "DLA_Translate"]
        );
        assert_eq!(names(&remove_our_plugins(&added).unwrap()), ["A"]);
    }

    #[test]
    fn removes_the_plugins_from_a_list_the_editor_saved_again() {
        let added = add_our_plugins(EDITOR_LIST).unwrap();
        let resaved = added.replace(
            "{\"name\":\"MessageWindowHidden\",\"status\":false",
            "{\"name\":\"MessageWindowHidden\",\"status\":true",
        );
        let removed = remove_our_plugins(&resaved).unwrap();
        assert_eq!(
            names(&removed),
            ["TorigoyaMZ_NotifyMessage", "MessageWindowHidden"]
        );
        assert!(removed.contains("\"status\":true,\"description\":\"\""));

        // Saved by the editor with a plugin added after ours.
        let reordered = added.replace(
            &format!(",\n{LAST_ENTRY}\n]"),
            &format!(
                ",\n{LAST_ENTRY},\n{{\"name\":\"Later\",\"status\":true,\"parameters\":{{}}}}\n]"
            ),
        );
        assert_eq!(
            names(&remove_our_plugins(&reordered).unwrap()),
            ["TorigoyaMZ_NotifyMessage", "MessageWindowHidden", "Later"]
        );
    }

    #[test]
    fn refuses_a_list_it_cannot_read() {
        assert_eq!(add_our_plugins("var plugins = 1;"), Err(UnknownLayout));
        assert_eq!(
            add_our_plugins("var $plugins = [{\"name\":}];"),
            Err(UnknownLayout)
        );
    }

    #[test]
    fn the_list_entries_match_the_plugin_descriptions() {
        for (file, script) in PLUGINS {
            let name = file.trim_end_matches(".js");
            let entry = [FIRST_ENTRY, LAST_ENTRY]
                .iter()
                .map(|entry| serde_json::from_str::<Value>(entry).unwrap())
                .find(|entry| entry["name"] == name)
                .unwrap();
            let description = entry["description"].as_str().unwrap();
            assert!(
                script.contains(&format!("@plugindesc {description}\n")),
                "{file}"
            );
        }
    }
}
